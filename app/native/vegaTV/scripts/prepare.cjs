const fs = require('fs');
const {execFileSync} = require('child_process');
const path = require('path');
const base = path.resolve(__dirname, '..');
const features = path.resolve(base, '../../src/features');
function prepare(alba = false, youtube = false) {
  const out = path.join(base, 'generated');
  fs.rmSync(out, {recursive: true, force: true});
  fs.mkdirSync(out, {recursive: true});
  const pack = require(path.join(features, 'stories/content/barca-2018-opening.json'));
  const playerUrl = process.env.ARENAVOCA_YOUTUBE_PLAYER_URL || 'http://10.0.2.2:8766/';
  fs.mkdirSync(path.join(out, 'youtube-player'), {recursive: true});
  const page = execFileSync(process.execPath, ['--experimental-strip-types', '--input-type=module', '-e',
    `import {youtubePlayerHtml} from ${JSON.stringify(require('url').pathToFileURL(path.join(features, 'tv-learning/vega/youtube.ts')).href)}; process.stdout.write(youtubePlayerHtml('WMjohb2tq7Y',808,36,0));`], {encoding: 'utf8'});
  fs.writeFileSync(path.join(out, 'youtube-player/index.html'), page);
  const youtubeSequence = {
    id: 'youtube-barca-2018-alba',
    title: 'Barcelona vs Madrid · 28 Oct 2018',
    duration: 36,
    details: 'Source: FC Barcelona YouTube channel\n' + pack.source.youtubeUrl +
      '\nRecording 13:28–14:04 · Prepared cards · Spanish awaits review',
    youtube: {videoId: 'WMjohb2tq7Y', startSeconds: 808},
    moments: pack.cards.filter(c => ['alba-run', 'alba-cutback', 'coutinho-goal'].includes(c.id))
      .map(c => ({id: c.id, title: c.title, spanish: c.spanish, english: c.english,
        end: c.evidence.endSeconds - 808, artwork: c.artwork})),
  };
  const sequence = alba
    ? {
        id: 'barca-2018-alba',
        title: 'Barcelona vs Madrid · 28 Oct 2018',
        duration: 36,
        details:
          'Recording 13:28–14:04\nSource: FC Barcelona YouTube channel\n' +
          pack.source.youtubeUrl +
          '\nPrepared match analysis · Spanish awaits review',
        moments: pack.cards
          .filter((c) =>
            ['alba-run', 'alba-cutback', 'coutinho-goal'].includes(c.id),
          )
          .map((c) => ({
            id: c.id,
            title: c.title,
            spanish: c.spanish,
            english: c.english,
            artwork: {
              'alba-run': 'comic_alba_run',
              'alba-cutback': 'comic_alba_cutback',
              'coutinho-goal': 'comic_alba_goal',
            }[c.id],
            end: c.evidence.endSeconds - 808,
          })),
      }
    : {
        id: 'original-football',
        title: 'Blue vs Amber',
        duration: 36,
        details:
          'Original illustrated sequence · Prepared learning cards · Spanish awaits review',
        moments: [
          {
            id: 'pass',
            title: 'The pass',
            spanish: 'El jugador pasa el balón.',
            english: 'The player passes the ball.',
            end: 8,
            artwork: 'action_pass',
          },
          {
            id: 'shot',
            title: 'The shot',
            spanish: 'El jugador dispara.',
            english: 'The player shoots.',
            end: 20,
            artwork: 'action_shot',
          },
          {
            id: 'save',
            title: 'The save',
            spanish: 'El portero para el balón.',
            english: 'The goalkeeper saves the ball.',
            end: 28,
            artwork: 'action_save',
          },
        ],
      };
  const media = alba
    ? path.resolve(base, '../local-media/tv/res/raw/tv_alba.mp4')
    : path.join(features, 'tv-learning/res/raw/tv_football.mp4');
  if (!fs.existsSync(media)) throw Error('Missing sequence: ' + media);
  fs.copyFileSync(media, path.join(out, 'match.mp4'));
  // The SDK's frozen native surface does not reliably resize after EOF.
  // Derive the actual final frame from this exact pack, without changing playback.
  execFileSync('ffmpeg', [
    '-v',
    'error',
    '-y',
    '-sseof',
    '-0.1',
    '-i',
    media,
    '-update',
    '1',
    '-q:v',
    '2',
    path.join(out, 'end-frame.jpg'),
  ]);
  for (const m of sequence.moments) {
    fs.copyFileSync(
      path.join(
        features,
        alba ? 'stories' : 'recap',
        'artwork/res/drawable-nodpi',
        m.artwork + '.png',
      ),
      path.join(out, m.artwork + '.png'),
    );
  }
  for (const m of youtubeSequence.moments) {
    fs.copyFileSync(path.join(features, 'stories/artwork/res/drawable-nodpi', m.artwork + '.png'),
      path.join(out, m.artwork + '.png'));
  }
  fs.writeFileSync(
    path.join(out, 'content.ts'),
    `// Generated by prepare.cjs; do not edit.\nexport const sequence = ${JSON.stringify(
      sequence,
      null,
      2,
    )};\nexport const enableYouTube = ${youtube};\nexport const youtubePlayerUrl = ${JSON.stringify(playerUrl)};\nexport const youtubeSequence = ${JSON.stringify(youtubeSequence, null, 2)};\nexport const videoAsset = require('./match.mp4');\nexport const endFrameAsset = require('./end-frame.jpg');\nexport const artwork: Record<string, number> = {\n${[...sequence.moments, ...youtubeSequence.moments]
      .map((m) => `  '${m.artwork}': require('./${m.artwork}.png'),`)
      .join('\n')}\n};\n`,
  );
  return sequence;
}
module.exports = {prepare};
if (require.main === module) prepare();
